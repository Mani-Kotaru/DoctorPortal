package com.java_operators;

public class BitwiseOperators {

	public static void main(String[] args) {
      int a=10;
      int b=2;
      System.out.println("a & b:"+ (a&b));
      System.out.println("a | b:"+ (a|b));
      System.out.println("a ^ b:"+ (a^b));
      System.out.println("~b:"+ (~b));
      System.out.println("a << b:"+ (a<<b));
      System.out.println("a >> b:"+ (a>>b));
      System.out.println("a >>> b:"+ (a>>>b));
	}

}
