package com.java_operators;
//WAP to demonstrate relational operators
public class RelationalOperators {

	public static void main(String[] args) {
     
		double a=5.9;
		double b=4.8;
		System.out.println(a==b);//false
		System.out.println(a!=b);//true
		System.out.println(a<=b);//false
		System.out.println(a>=b);//true
		System.out.println(a<b);//false
		System.out.println(a>b);//true
		
	}

}
